"""
AERIS AI - AQI Prediction View
Interactive ML-based Air Quality Index estimation using trained regression models.
"""
import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
from pathlib import Path

import config
from services.prediction_service import PredictionService
from services.recommendation_service import RecommendationService
from components.metric_cards import render_hero_banner, render_metric_card
from components.charts import apply_dark_theme

@st.cache_resource
def get_prediction_service():
    return PredictionService()

def render_prediction_view():
    """Render the Machine Learning AQI Estimation page."""
    pred_service = get_prediction_service()
    metrics_data = pred_service.get_metrics()

    render_hero_banner(
        title="ML-Based AQI Estimation",
        subtitle="Predict Air Quality Index from atmospheric pollutant concentrations using trained regression models.",
        badge_text="PREDICTIVE ENGINE",
        badge_color="#22D3EE"
    )

    # Statistical notice
    st.markdown("""
    <div style="
        background: rgba(34, 211, 238, 0.08);
        border: 1px solid rgba(34, 211, 238, 0.3);
        border-radius: 10px;
        padding: 0.65rem 1rem;
        margin-bottom: 1.25rem;
        display: flex;
        align-items: center;
        gap: 0.6rem;
    ">
        <span style="font-size: 1.1rem;">🧠</span>
        <div style="font-size: 0.85rem; color: #94A3B8;">
            <strong style="color: #22D3EE;">Machine Learning Estimate:</strong>
            Outputs are statistical estimates generated by regressors trained on 7,300+ CPCB metropolitan observation records. This is not a sensor reading or future forecast.
        </div>
    </div>
    """, unsafe_allow_html=True)

    col_inputs, col_results = st.columns([0.52, 0.48])

    with col_inputs:
        st.markdown("""
        <div style="font-size: 1.05rem; font-weight: 700; color: #F8FAFC; margin-bottom: 0.75rem;">
            ⚙️ Pollutant Input Parameters
        </div>
        """, unsafe_allow_html=True)

        model_options = [
            "Random Forest Regressor (Recommended)",
            "Decision Tree Regressor",
            "Linear Regression"
        ]
        selected_model_str = st.selectbox(
            "Select Prediction Architecture",
            options=model_options,
            index=0,
            help="Choose the regression architecture used for AQI inference."
        )

        st.markdown("<div style='height: 0.35rem;'></div>", unsafe_allow_html=True)

        # Quick preset buttons
        st.markdown("""
        <div style="font-size: 0.75rem; color: #94A3B8; text-transform: uppercase; font-weight: 600; margin-bottom: 0.3rem;">
            Preset Atmospheric Profiles
        </div>
        """, unsafe_allow_html=True)
        btn_col1, btn_col2, btn_col3 = st.columns(3)
        
        # State keys for presets
        if "preset_pm25" not in st.session_state:
            st.session_state.preset_pm25 = 124.5
            st.session_state.preset_pm10 = 210.0
            st.session_state.preset_no2 = 48.0
            st.session_state.preset_so2 = 18.5
            st.session_state.preset_co = 2.4
            st.session_state.preset_o3 = 35.0

        with btn_col1:
            if st.button("🌱 Clean / Monsoon", use_container_width=True, type="secondary"):
                st.session_state.preset_pm25 = 25.0
                st.session_state.preset_pm10 = 55.0
                st.session_state.preset_no2 = 20.0
                st.session_state.preset_so2 = 10.0
                st.session_state.preset_co = 0.8
                st.session_state.preset_o3 = 25.0
                st.rerun()
        with btn_col2:
            if st.button("⚠️ Moderate Urban", use_container_width=True, type="secondary"):
                st.session_state.preset_pm25 = 85.0
                st.session_state.preset_pm10 = 150.0
                st.session_state.preset_no2 = 45.0
                st.session_state.preset_so2 = 18.0
                st.session_state.preset_co = 1.6
                st.session_state.preset_o3 = 38.0
                st.rerun()
        with btn_col3:
            if st.button("🛑 Winter Smog", use_container_width=True, type="secondary"):
                st.session_state.preset_pm25 = 260.0
                st.session_state.preset_pm10 = 420.0
                st.session_state.preset_no2 = 82.0
                st.session_state.preset_so2 = 26.0
                st.session_state.preset_co = 3.5
                st.session_state.preset_o3 = 52.0
                st.rerun()

        st.markdown("<div style='height: 0.5rem;'></div>", unsafe_allow_html=True)

        col_p1, col_p2 = st.columns(2)
        with col_p1:
            pm25 = st.slider("PM2.5 (µg/m³)", min_value=0.0, max_value=500.0, value=float(st.session_state.preset_pm25), step=0.5, help="Fine Particulate Matter (CPCB limit: 60)")
            pm10 = st.slider("PM10 (µg/m³)", min_value=0.0, max_value=800.0, value=float(st.session_state.preset_pm10), step=1.0, help="Respirable Particulate Matter (CPCB limit: 100)")
            no2 = st.slider("NO₂ (µg/m³)", min_value=0.0, max_value=300.0, value=float(st.session_state.preset_no2), step=1.0, help="Nitrogen Dioxide (CPCB limit: 80)")
            
        with col_p2:
            so2 = st.slider("SO₂ (µg/m³)", min_value=0.0, max_value=200.0, value=float(st.session_state.preset_so2), step=0.5, help="Sulfur Dioxide (CPCB limit: 80)")
            co = st.slider("CO (mg/m³)", min_value=0.0, max_value=25.0, value=float(st.session_state.preset_co), step=0.1, help="Carbon Monoxide (CPCB limit: 4.0)")
            o3 = st.slider("O₃ (µg/m³)", min_value=0.0, max_value=250.0, value=float(st.session_state.preset_o3), step=1.0, help="Ozone (CPCB limit: 100)")

    # Execute Inference via Service
    features = {
        "PM2.5": pm25, "PM10": pm10, "NO2": no2,
        "SO2": so2, "CO": co, "O3": o3
    }
    pred_result = pred_service.predict_aqi(features, model_name=selected_model_str)
    category = pred_result["category"]
    est_val = pred_result["estimated_aqi"]

    with col_results:
        st.markdown("""
        <div style="font-size: 1.05rem; font-weight: 700; color: #F8FAFC; margin-bottom: 0.75rem;">
            📊 ML Estimation Output
        </div>
        """, unsafe_allow_html=True)

        st.markdown(f"""
        <div style="
            background: #192630;
            border: 2px solid {category['color']}66;
            border-radius: 14px;
            padding: 1.5rem;
            box-shadow: 0 8px 24px rgba(0,0,0,0.5);
            margin-bottom: 1.25rem;
        ">
            <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 0.75rem;">
                <span style="font-size: 0.75rem; color: #94A3B8; text-transform: uppercase; font-weight: 700; letter-spacing: 0.05em;">
                    Estimated Output
                </span>
                <span style="
                    background: {category['badge_bg']};
                    color: {category['color']};
                    border: 1px solid {category['color']};
                    padding: 0.25rem 0.75rem;
                    border-radius: 20px;
                    font-size: 0.8rem;
                    font-weight: 700;
                ">
                    {category['icon']} {category['label']}
                </span>
            </div>
            
            <div style="display: flex; align-items: baseline; gap: 0.75rem;">
                <span style="
                    font-size: 3.5rem;
                    font-weight: 800;
                    color: {category['color']};
                    line-height: 1;
                ">
                    {int(est_val)}
                </span>
                <div>
                    <span style="font-size: 1.1rem; color: #94A3B8; font-weight: 600;">AQI Estimate</span>
                    <div style="font-size: 0.75rem; color: #10B981;">Latency: {pred_result['latency_ms']} ms</div>
                </div>
            </div>
            
            <div style="
                margin-top: 1rem;
                padding-top: 0.85rem;
                border-top: 1px solid #293946;
                font-size: 0.85rem;
                color: #F8FAFC;
                line-height: 1.5;
            ">
                <strong>Model:</strong> {pred_result['model_name']}<br>
                <span style="color: #94A3B8;">{category['description']}</span>
            </div>
            
            <div style="
                margin-top: 0.85rem;
                font-size: 0.72rem;
                color: #22D3EE;
                font-weight: 600;
            ">
                * Note: Statistically inferred using multi-variate regression.
            </div>
        </div>
        """, unsafe_allow_html=True)

        # Active Model Performance Scorecard
        model_metrics = pred_result["metrics"]
        st.markdown(f"""
        <div style="
            background: #141E27;
            border: 1px solid #293946;
            border-radius: 12px;
            padding: 1.25rem;
        ">
            <div style="font-size: 0.82rem; font-weight: 700; color: #F8FAFC; margin-bottom: 0.75rem; text-transform: uppercase; letter-spacing: 0.05em;">
                📈 Verified Test Benchmark ({pred_result['model_name']})
            </div>
            <div style="display: grid; grid-template-columns: 1fr 1fr 1fr; gap: 0.75rem; text-align: center;">
                <div style="background: #192630; border: 1px solid #293946; border-radius: 8px; padding: 0.6rem 0.4rem;">
                    <div style="font-size: 0.7rem; color: #94A3B8; font-weight: 600;">R² SCORE</div>
                    <div style="font-size: 1.2rem; font-weight: 800; color: #10B981; margin-top: 0.2rem;">{model_metrics.get('R2', '--')}</div>
                </div>
                <div style="background: #192630; border: 1px solid #293946; border-radius: 8px; padding: 0.6rem 0.4rem;">
                    <div style="font-size: 0.7rem; color: #94A3B8; font-weight: 600;">MAE</div>
                    <div style="font-size: 1.2rem; font-weight: 800; color: #22D3EE; margin-top: 0.2rem;">{model_metrics.get('MAE', '--')}</div>
                </div>
                <div style="background: #192630; border: 1px solid #293946; border-radius: 8px; padding: 0.6rem 0.4rem;">
                    <div style="font-size: 0.7rem; color: #94A3B8; font-weight: 600;">RMSE</div>
                    <div style="font-size: 1.2rem; font-weight: 800; color: #F8FAFC; margin-top: 0.2rem;">{model_metrics.get('RMSE', '--')}</div>
                </div>
            </div>
            <div style="font-size: 0.72rem; color: #64748B; margin-top: 0.75rem;">
                Evaluated on 1,462 independent test holdout samples (80/20 CPCB split).
            </div>
        </div>
        """, unsafe_allow_html=True)

    st.markdown("<hr style='border: 0; border-top: 1px solid #293946; margin: 1.5rem 0;'>", unsafe_allow_html=True)

    # Multi-Model Benchmark Comparison Section
    st.markdown("""
    <div style="font-size: 1.15rem; font-weight: 700; color: #F8FAFC; margin-bottom: 0.75rem;">
        🔬 Multi-Model Evaluation Comparison
    </div>
    """, unsafe_allow_html=True)

    comp_tab1, comp_tab2 = st.columns([0.55, 0.45])

    with comp_tab1:
        # Table of all models
        if "metrics" in metrics_data:
            summary_rows = []
            for m_name, m_scores in metrics_data["metrics"].items():
                summary_rows.append({
                    "Architecture": m_name,
                    "R² (Accuracy)": m_scores["R2"],
                    "MAE (Mean Error)": m_scores["MAE"],
                    "RMSE": m_scores["RMSE"],
                    "Status": "Optimal" if m_scores["R2"] >= 0.99 else "Strong Baseline"
                })
            st.dataframe(pd.DataFrame(summary_rows), use_container_width=True, hide_index=True)

    with comp_tab2:
        # Feature Importances for Random Forest
        feat_analysis = metrics_data.get("feature_analysis", {})
        if "rf_importances" in feat_analysis:
            imp_df = pd.DataFrame({
                "Feature": feat_analysis["features"],
                "Importance": feat_analysis["rf_importances"]
            }).sort_values("Importance", ascending=True)

            fig_imp = px.bar(
                imp_df,
                x="Importance",
                y="Feature",
                orientation='h',
                color="Importance",
                color_continuous_scale=["#22D3EE", "#10B981"],
                text="Importance"
            )
            apply_dark_theme(fig_imp, "Random Forest Feature Relative Importance")
            fig_imp.update_layout(height=260, coloraxis_showscale=False, yaxis_title="")
            st.plotly_chart(fig_imp, use_container_width=True)

    # Evaluation Residuals / Scatter Plot Expander
    eval_csv = config.MODELS_DIR / "test_evaluation_data.csv"
    if eval_csv.exists():
        with st.expander("📈 Test Holdout Evaluation Distribution (Actual vs Predicted)", expanded=False):
            eval_sample = pd.read_csv(eval_csv).head(250)
            fig_scatter = go.Figure()
            fig_scatter.add_trace(go.Scatter(
                x=eval_sample["Actual_AQI"],
                y=eval_sample["Pred_random_forest"] if "Pred_random_forest" in eval_sample.columns else eval_sample["Actual_AQI"],
                mode='markers',
                name='Random Forest',
                marker=dict(color='#10B981', size=6, opacity=0.8)
            ))
            fig_scatter.add_trace(go.Scatter(
                x=[0, 500], y=[0, 500],
                mode='lines',
                name='Ideal 1:1 Parity',
                line=dict(color='#EF4444', dash='dash')
            ))
            apply_dark_theme(fig_scatter, "Random Forest: Actual AQI vs Predicted AQI (Holdout Test Set)")
            fig_scatter.update_layout(
                xaxis_title="Actual Ground-Truth AQI",
                yaxis_title="Predicted Model AQI",
                height=350
            )
            st.plotly_chart(fig_scatter, use_container_width=True)
